"""Deliverable 4: results table + reported resource usage, generated from run artifacts.

Reads the ledger, the run's console log, the audited scorer log and the shipped
submission.csv. Every number is derived; none is typed in. The hidden-test row is scored
with the organizers' own evaluate.py, not with our fast kernel, so the table cannot be
higher than what a judge recomputes.

The one hand-written part is the closing note in reports/_results_note.md, appended
verbatim and labelled as prose. It contains no numbers that are not also derived above it.

    ./.venv/bin/python experiments/results_table.py
"""
import csv, json, os, sys

sys.path.insert(0, '.')

# Published official-baseline scores from the problem statement (5-seed means).
# experiments/verify_baseline.py reproduces these from the shipped baseline.py.
BASELINE = {'GAUC': 0.6610, 'nDCG@5': 0.5282, 'primary': 0.5946,
            'valid_GAUC': 0.6674, 'valid_nDCG@5': 0.5357, 'valid_primary': 0.6016}

RUN_DIR = 'runs/kairos_submission_repro'   # the campaign that produced submission.csv
RUN_LOG = 'runs/live_submission.log'       # its console output, incl. the stop reason
NOTE = 'reports/_results_note.md'


def stop_reason(log_path):
    """The run's ACTUAL terminating condition, read from its console output.

    Not inferred and not assumed to be the convergence rule: the loop checks the token
    budget before it checks convergence, so a run can end with the eps/N rule still
    unfired. Reporting 'converged' when the log says otherwise would be a claim the
    committed evidence contradicts.
    """
    if not os.path.exists(log_path):
        return None, None
    for line in open(log_path):
        if line.startswith('STOPPED:') or line.startswith('CONVERGED:'):
            kind, _, detail = line.strip().partition(':')
            return kind, detail.strip()
    return None, None


def tokens_by_model(log_path):
    """Pull the run's per-model token block out of its console log.

    The loop prints a JSON summary at the end; we want one nested object out of it. Brace
    counting rather than a regex, so nesting cannot truncate the match.
    """
    if not os.path.exists(log_path):
        return None
    txt = open(log_path).read()
    i = txt.find('"tokens_by_model"')
    if i < 0:
        return None
    start = txt.find('{', i)
    if start < 0:
        return None
    depth = 0
    for j in range(start, len(txt)):
        if txt[j] == '{':
            depth += 1
        elif txt[j] == '}':
            depth -= 1
            if depth == 0:
                try:
                    return json.loads(txt[start:j + 1])
                except json.JSONDecodeError:
                    return None
    return None


def test_scores(submission='submission.csv', data_dir=None):
    """Score the shipped submission with the OFFICIAL evaluate.py."""
    import data as official_data
    import evaluate as official_eval
    data_dir = data_dir or os.environ.get('KUAIRAND_PURE', 'KuaiRand-Pure/data')
    if not os.path.exists(submission) or not os.path.isdir(data_dir):
        return None
    test = official_data.load(data_dir)['test']
    rows = list(csv.DictReader(open(submission)))
    if len(rows) != len(test):
        return None
    m = official_eval.evaluate([r[1] for r in test], [r[6] for r in test],
                               [float(r['score']) for r in rows])
    return {'GAUC': m['GAUC'], 'nDCG@5': m['nDCG@5'], 'primary': m['primary']}


def main(run_dir=RUN_DIR, out='reports/RESULTS.md', run_log=RUN_LOG):
    entries = [json.loads(l) for l in open(os.path.join(run_dir, 'ledger.jsonl')) if l.strip()]
    scored = [e for e in entries
              if (e.get('outcome') or {}).get('valid_primary') is not None
              and (e.get('outcome') or {}).get('valid_primary') == (e.get('outcome') or {}).get('valid_primary')]
    best = max(scored, key=lambda e: e['outcome']['valid_primary']) if scored else None
    last_budget = (entries[-1].get('budget') or {}) if entries else {}
    n_int = sum(int(e.get('interventions') or 0) for e in entries)
    n_accept = sum(1 for e in entries if e.get('decision') == 'accept')

    err_path = os.path.join(run_dir, 'ledger_errors.jsonl')
    n_err = sum(1 for _ in open(err_path)) if os.path.exists(err_path) else 0

    from kairos.kernel.dataset import STRICT_TRAIN_SPLIT

    L = ['# Results — KuaiRand-Pure (required benchmark)', '',
         'Generated by `experiments/results_table.py` from the run ledger, the run log, the',
         'audited scorer log, and the shipped `submission.csv`. The hidden-test row is scored',
         "with the organizers' unmodified `evaluate.py`.", '',
         f'Campaign: `{run_dir}`. The submission is the **validation-best checkpoint** at the',
         'point the run stopped, scored once on the hidden test split.', '',
         '## Validation-best result', '']
    if best:
        o = best['outcome']
        L += ['| metric | official baseline | KAIROS (validation-best) | absolute delta |',
              '|---|---|---|---|',
              f"| GAUC | {BASELINE['valid_GAUC']:.4f} | {o['valid_gauc']:.4f} | {o['valid_gauc']-BASELINE['valid_GAUC']:+.4f} |",
              f"| nDCG@5 | {BASELINE['valid_nDCG@5']:.4f} | {o['valid_ndcg']:.4f} | {o['valid_ndcg']-BASELINE['valid_nDCG@5']:+.4f} |",
              f"| **primary** | **{BASELINE['valid_primary']:.4f}** | **{o['valid_primary']:.4f}** | **{o['valid_primary']-BASELINE['valid_primary']:+.4f}** |",
              '', f"Accepted at iteration {best.get('iteration')} of {len(entries)}"
              f" ({n_accept} accepts in the run).", '']

    t = test_scores()
    if t:
        L += ['## Hidden-test result (one consultation, at the end)', '',
              '| metric | official baseline | KAIROS | absolute delta |', '|---|---|---|---|',
              f"| GAUC | {BASELINE['GAUC']:.4f} | {t['GAUC']:.4f} | **{t['GAUC']-BASELINE['GAUC']:+.4f}** |",
              f"| nDCG@5 | {BASELINE['nDCG@5']:.4f} | {t['nDCG@5']:.4f} | **{t['nDCG@5']-BASELINE['nDCG@5']:+.4f}** |",
              f"| primary | {BASELINE['primary']:.4f} | {t['primary']:.4f} | **{t['primary']-BASELINE['primary']:+.4f}** |", '']
        sd = ((t['GAUC'] - BASELINE['GAUC']) + (t['nDCG@5'] - BASELINE['nDCG@5'])) / 2
        L += [f"`score_dataset` = mean of the per-metric deltas = **{sd:+.4f}**.", '',
              'Reproduce this row directly from the submission file:',
              '`./.venv/bin/python experiments/verify_submission.py`', '']

    L += ['## Resource usage (Feasibility & Practicality)', '',
          '| quantity | value |', '|---|---|',
          f"| Iterations used | {len(entries)} / 50 |",
          f"| Wall-clock | {last_budget.get('wall_clock_s','?')} s |"]
    tin, tout = last_budget.get('tokens_in'), last_budget.get('tokens_out')
    if isinstance(tin, int) and isinstance(tout, int):
        L += [f"| Tokens in | {tin:,} |", f"| Tokens out | {tout:,} |",
              f"| **Tokens total** | **{tin+tout:,}** |"]
    L += [f"| **Manual interventions** | **{n_int}** |",
          '| GPU-hours | 0 (CPU only) |', '']

    # Per-model token split, if the run log recorded it. Scanned by brace balance rather
    # than by regex - the block is nested and a non-greedy pattern closes on the wrong
    # brace, which silently drops the table instead of failing.
    by = tokens_by_model(run_log)
    if by:
        L += ['Split by model:', '', '| model | role | in | out | calls |',
              '|---|---|---|---|---|']
        roles = {'claude-opus-5': 'planner', 'claude-sonnet-5': 'coder'}
        for k, v in by.items():
            L += [f"| `{k}` | {roles.get(k,'')} | {v.get('in',0):,} |"
                  f" {v.get('out',0):,} | {v.get('calls',0)} |"]
        L += [f"| **total** | | **{sum(v.get('in',0) for v in by.values()):,}** |"
              f" **{sum(v.get('out',0) for v in by.values()):,}** |"
              f" **{sum(v.get('calls',0) for v in by.values())}** |", '']

    L += ['## Run configuration and how the run ended', '']
    kind, detail = stop_reason(run_log)
    L += ['- Convergence rule **declared before the run**, as FAQ 2.9.1 permits:',
          '  eps = 0.002, N = 5, minimum-iteration floor = 10',
          '- Hard caps respected: 50 iterations, 6 h wall-clock',
          '- Self-imposed token budget: 150,000']
    if kind == 'STOPPED':
        L += [f'- **How the run actually ended: {detail}**',
              '  The declared eps/N rule was in force but never fired — the loop checks the',
              '  token budget first. The scored submission is still the validation-best',
              '  checkpoint at the point the run stopped, per FAQ 2.9.1(c).']
    elif kind == 'CONVERGED':
        L += [f'- **How the run actually ended:** converged — {detail}']
    L += [f"- Training-split reading: **{'strict' if STRICT_TRAIN_SPLIT else 'permissive'}** "
          f"(`KAIROS_STRICT_TRAIN_SPLIT`) — see `reports/DATA_DISCIPLINE.md`",
          f'- Logged error / recovery events: {n_err} (see `{os.path.basename(err_path)}`)', '']

    audit = 'runs/scorer_audit.log'
    if os.path.exists(audit):
        n = sum(1 for _ in open(audit))
        L += ['## Audited consultations of the hidden test split', '',
              f'**{n}** across the whole project, each timestamped with its reason in',
              '`runs/scorer_audit.log`. None informed candidate selection: the loop compares',
              '`valid_primary` only.', '']

    if os.path.exists(NOTE):
        L += [open(NOTE).read().rstrip(), '']

    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    open(out, 'w').write('\n'.join(L))
    print(f'  wrote {out}')
    if best:
        print(f"  validation-best: {best['outcome']['valid_primary']:.4f} "
              f"(delta {best['outcome']['valid_primary']-BASELINE['valid_primary']:+.4f})")
    if t:
        print(f"  hidden test:     {t['primary']:.4f} "
              f"(delta {t['primary']-BASELINE['primary']:+.4f})")


if __name__ == '__main__':
    main(*(sys.argv[1:] or []))
