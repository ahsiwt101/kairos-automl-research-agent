"""Deliverable 4: results table + reported resource usage, generated from run artifacts.

Reads the ledger and the scorer audit log. Nothing is typed in by hand, so the reported
numbers cannot drift from what the run actually produced.
"""
import json, os, sys
sys.path.insert(0, '.')

BASELINE = {'GAUC': 0.6610, 'nDCG@5': 0.5282, 'primary': 0.5946,
            'valid_GAUC': 0.6674, 'valid_nDCG@5': 0.5357, 'valid_primary': 0.6016}

def main(run_dir='runs/kairos_live', out='reports/RESULTS.md'):
    entries = [json.loads(l) for l in open(os.path.join(run_dir, 'ledger.jsonl')) if l.strip()]
    scored = [e for e in entries
              if (e.get('outcome') or {}).get('valid_primary') == (e.get('outcome') or {}).get('valid_primary')
              and (e.get('outcome') or {}).get('valid_primary') is not None]
    best = max(scored, key=lambda e: e['outcome']['valid_primary']) if scored else None
    last_budget = (entries[-1].get('budget') or {}) if entries else {}
    n_int = sum(int(e.get('interventions') or 0) for e in entries)

    from kairos.kernel.dataset import STRICT_TRAIN_SPLIT

    L = ['# Results — KuaiRand-Pure (required benchmark)', '',
         'Generated by `experiments/results_table.py` from the run ledger and the audited',
         'scorer log. The submission is the **validation-best checkpoint** at convergence,',
         'scored once on the hidden test split.', '',
         '## Validation-best result', '']
    if best:
        o = best['outcome']
        L += ['| metric | official baseline | KAIROS (validation-best) | absolute delta |',
              '|---|---|---|---|',
              f"| GAUC | {BASELINE['valid_GAUC']:.4f} | {o['valid_gauc']:.4f} | {o['valid_gauc']-BASELINE['valid_GAUC']:+.4f} |",
              f"| nDCG@5 | {BASELINE['valid_nDCG@5']:.4f} | {o['valid_ndcg']:.4f} | {o['valid_ndcg']-BASELINE['valid_nDCG@5']:+.4f} |",
              f"| **primary** | **{BASELINE['valid_primary']:.4f}** | **{o['valid_primary']:.4f}** | **{o['valid_primary']-BASELINE['valid_primary']:+.4f}** |",
              '', f"Accepted at iteration {best.get('iteration')}.", '']
    else:
        L += ['_No scored iteration in this run._', '']

    L += ['## Resource usage (Feasibility & Practicality)', '',
          '| quantity | value |', '|---|---|',
          f"| Iterations used | {len(entries)} / 50 |",
          f"| Wall-clock | {last_budget.get('wall_clock_s','?')} s |",
          f"| Tokens in | {last_budget.get('tokens_in','?'):,} |" if isinstance(last_budget.get('tokens_in'), int) else "| Tokens in | ? |",
          f"| Tokens out | {last_budget.get('tokens_out','?'):,} |" if isinstance(last_budget.get('tokens_out'), int) else "| Tokens out | ? |",
          f"| **Manual interventions** | **{n_int}** |",
          '| GPU-hours | 0 (CPU only) |', '',
          '## Run configuration', '',
          f"- Convergence rule: eps = 0.002, N = 3 (organizer default)",
          f"- Training-split reading: **{'strict' if STRICT_TRAIN_SPLIT else 'permissive'}** "
          f"(`KAIROS_STRICT_TRAIN_SPLIT`) — see `reports/DATA_DISCIPLINE.md`",
          '']

    audit = 'runs/scorer_audit.log'
    if os.path.exists(audit):
        n = sum(1 for _ in open(audit))
        L += ['## Audited consultations of the hidden test split', '',
              f'**{n}**, each timestamped with its reason in `runs/scorer_audit.log`. None',
              'informed candidate selection: the loop compares `valid_primary` only.', '']

    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    open(out, 'w').write('\n'.join(L))
    print(f'  wrote {out}')
    if best:
        print(f"  validation-best: {best['outcome']['valid_primary']:.4f} "
              f"(delta {best['outcome']['valid_primary']-BASELINE['valid_primary']:+.4f})")

if __name__ == '__main__':
    main(*(sys.argv[1:] or []))
